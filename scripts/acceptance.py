#!/usr/bin/env python3
"""End-to-end acceptance against a generated, real git repository."""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from tests.support import add_incremental_commit, create_demo_repo, run_cli  # noqa: E402


def _json_command(fixture, label: str, args: List[str]) -> Dict[str, Any]:
    result = run_cli(fixture, [*args, "--json"])
    if result.returncode != 0:
        raise RuntimeError(
            f"{label} failed with exit {result.returncode}\n"
            f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
    return json.loads(result.stdout)


def _check(checks: List[Dict[str, str]], name: str, condition: bool, evidence: str) -> None:
    if not condition:
        raise AssertionError(f"{name}: {evidence}")
    checks.append({"name": name, "evidence": evidence})


def _markdown_report(
    checks: List[Dict[str, str]],
    initial: Dict[str, Any],
    search_field: Dict[str, Any],
    alice: Dict[str, Any],
    legacy: Dict[str, Any],
    gateway: Dict[str, Any],
    notes: Dict[str, Any],
    updated: Dict[str, Any],
    util: Dict[str, Any],
) -> str:
    generated = datetime.now(timezone.utc).isoformat(timespec="seconds")
    git_version = subprocess.run(
        ["git", "--version"], capture_output=True, text=True, check=True
    ).stdout.strip()
    scan = initial["scan"]
    updated_scan = updated["scan"]
    lines = [
        "# Acceptance report",
        "",
        f"Generated: `{generated}`  ",
        f"Environment: Python `{platform.python_version()}`, `{git_version}`  ",
        "Fixture: a throwaway git repository generated by `scripts/acceptance.py`.",
        "",
        "## Checks",
        "",
        "| # | Check | Evidence |",
        "|---|-------|----------|",
    ]
    for index, item in enumerate(checks, start=1):
        lines.append(f"| {index} | {item['name']} | {item['evidence']} |")
    lines.extend(
        [
            "",
            "## Initial scan",
            "",
            f"- Files: **{scan['file_count']}**",
            f"- Direct ownership: **{scan['direct_count']}**",
            f"- Fallback ownership: **{scan['fallback_count']}**",
            f"- Unassigned: **{scan['unassigned_count']}**",
            f"- Commits in window: **{scan['commit_count']}**",
            f"- Unmapped top authors: **{scan['unmapped_author_count']}**",
            "",
            "Search field (`SEARCH`) files:",
            "",
        ]
    )
    lines.extend(f"- `{item['path']}` ({item['assignment']})" for item in search_field["files"])
    lines.extend(
        [
            "",
            "Alice (`1001`) responsible files:",
            "",
        ]
    )
    lines.extend(
        f"- `{item['path']}` - {item['responsibility']}" for item in alice["files"]
    )
    lines.extend(
        [
            "",
            "## Fallback evidence",
            "",
            f"- `services/search/legacy_ranker.py`: field `{legacy['field_id']}`, "
            f"top author `{legacy['top_author_email']}` (unmapped), "
            f"source `{legacy['fallback_source_path']}`, "
            f"directory distance `{legacy['fallback_distance']}`.",
            f"- `services/payment/adapters/v2/gateway.py`: field `{gateway['field_id']}`, "
            f"source `{gateway['fallback_source_path']}`, "
            f"directory distance `{gateway['fallback_distance']}`.",
            f"- `services/search/notes.md`: `{notes['assignment']}`, "
            f"field `{notes['field_id']}`, source `{notes['fallback_source_path']}`.",
            "",
            "## Incremental rescan",
            "",
            f"- New scan id: **{updated_scan['id']}**",
            f"- Files: **{updated_scan['file_count']}**",
            f"- Direct / fallback / unassigned: **{updated_scan['direct_count']} / "
            f"{updated_scan['fallback_count']} / {updated_scan['unassigned_count']}**",
            f"- `services/shared_util.py` moved to field **{util['field_id']}** "
            f"with top employee **{util['top_employee_id']}**, churn **{util['churn']}**.",
            "",
            "## Reproduce",
            "",
            "```bash",
            "make accept",
            "# or",
            "python3 scripts/acceptance.py --keep-dir ./demo-workdir --report docs/acceptance-report.md",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--keep-dir",
        metavar="PATH",
        help="create the demo repository under PATH instead of a temporary directory",
    )
    parser.add_argument(
        "--report",
        metavar="PATH",
        help="write a Markdown acceptance report",
    )
    args = parser.parse_args()

    temp_handle = None
    if args.keep_dir:
        base = Path(args.keep_dir).expanduser().resolve()
        if base.exists() and any(base.iterdir()):
            print(f"error: {base} already exists and is not empty", file=sys.stderr)
            return 1
        base.mkdir(parents=True, exist_ok=True)
    else:
        temp_handle = tempfile.TemporaryDirectory(prefix="gitfield-acceptance-")
        base = Path(temp_handle.name)

    checks: List[Dict[str, str]] = []
    try:
        fixture = create_demo_repo(base)
        print("gitfield acceptance")
        print("===================")
        print(f"Fixture repository: {fixture.repo}")
        print(f"Database:           {fixture.database}")
        print()

        scan_args = [
            "--db",
            str(fixture.database),
            "scan",
            "--repo",
            str(fixture.repo),
            "--roster",
            str(fixture.roster),
            "--author-map",
            str(fixture.author_map),
        ]
        initial = _json_command(fixture, "initial scan", scan_args)
        scan = initial["scan"]
        _check(
            checks,
            "window uses two years by default",
            scan["since_ts"] < scan["until_ts"],
            f"{scan['since_ts']} -> {scan['until_ts']}",
        )
        _check(
            checks,
            "all current files assigned",
            scan["file_count"] == 8 and scan["unassigned_count"] == 0,
            f"{scan['file_count']} files, 0 unassigned",
        )
        _check(
            checks,
            "direct and fallback split",
            scan["direct_count"] == 5 and scan["fallback_count"] == 3,
            f"direct={scan['direct_count']}, fallback={scan['fallback_count']}",
        )
        print(
            f"[1] scan             files={scan['file_count']} direct={scan['direct_count']} "
            f"fallback={scan['fallback_count']} commits={scan['commit_count']}"
        )

        search_field = _json_command(
            fixture,
            "field query",
            ["--db", str(fixture.database), "field", "SEARCH"],
        )
        _check(
            checks,
            "field query returns all field files",
            search_field["count"] == 4,
            f"SEARCH files={search_field['count']}",
        )
        print(f"[2] field SEARCH     files={search_field['count']}")

        alice = _json_command(
            fixture,
            "employee query",
            ["--db", str(fixture.database), "employee", "1001"],
        )
        _check(
            checks,
            "employee query includes direct and accountable fallback files",
            alice["count"] == 3,
            f"1001 responsible files={alice['count']}",
        )
        alice_direct = _json_command(
            fixture,
            "direct employee query",
            [
                "--db",
                str(fixture.database),
                "employee",
                "1001",
                "--direct-only",
            ],
        )
        _check(
            checks,
            "direct-only employee query filters fallback",
            alice_direct["count"] == 2,
            f"1001 direct files={alice_direct['count']}",
        )
        print(
            f"[3] employee 1001    responsible={alice['count']} "
            f"direct={alice_direct['count']}"
        )

        legacy = _json_command(
            fixture,
            "legacy file query",
            [
                "--db",
                str(fixture.database),
                "file",
                "services/search/legacy_ranker.py",
            ],
        )
        _check(
            checks,
            "departed top author is marked and inherits sibling ownership",
            legacy["assignment"] == "fallback_unmapped_author"
            and legacy["field_id"] == "SEARCH"
            and legacy["fallback_source_path"] == "services/search/index.py"
            and legacy["fallback_distance"] == 0,
            "SEARCH via services/search/index.py at distance 0",
        )
        print(
            f"[4] fallback sibling {legacy['field_id']} via "
            f"{legacy['fallback_source_path']} distance={legacy['fallback_distance']}"
        )

        gateway = _json_command(
            fixture,
            "gateway file query",
            [
                "--db",
                str(fixture.database),
                "file",
                "services/payment/adapters/v2/gateway.py",
            ],
        )
        _check(
            checks,
            "recursive directory fallback finds the nearest direct file",
            gateway["field_id"] == "PAY"
            and gateway["fallback_source_path"] == "services/payment/charge.py"
            and gateway["fallback_distance"] == 2,
            "PAY via services/payment/charge.py at distance 2",
        )
        print(
            f"[5] fallback nested  {gateway['field_id']} via "
            f"{gateway['fallback_source_path']} distance={gateway['fallback_distance']}"
        )

        notes = _json_command(
            fixture,
            "no-history file query",
            [
                "--db",
                str(fixture.database),
                "file",
                "services/search/notes.md",
            ],
        )
        _check(
            checks,
            "file without in-window history is marked separately",
            notes["assignment"] == "fallback_no_history"
            and notes["field_id"] == "SEARCH",
            "fallback_no_history -> SEARCH",
        )
        print(f"[6] no-history file  {notes['assignment']} -> {notes['field_id']}")

        charge = _json_command(
            fixture,
            "charge file query",
            [
                "--db",
                str(fixture.database),
                "file",
                "services/payment/charge.py",
            ],
        )
        _check(
            checks,
            "old history outside the window is ignored",
            charge["top_employee_id"] == "1001" and charge["churn"] == 4,
            "1001 with churn 4, not the four-year-old contributor",
        )
        print(
            f"[7] recent churn     charge top={charge['top_employee_id']} "
            f"churn={charge['churn']}"
        )

        summary = _json_command(
            fixture,
            "summary query",
            ["--db", str(fixture.database), "summary"],
        )
        _check(
            checks,
            "summary exposes unmapped top authors",
            len(summary["unmapped_top_authors"]) == 2,
            "2 unmapped top authors",
        )
        print(
            f"[8] summary          unmapped_top_authors="
            f"{len(summary['unmapped_top_authors'])}"
        )

        add_incremental_commit(fixture)
        updated = _json_command(fixture, "incremental scan", scan_args)
        updated_scan = updated["scan"]
        _check(
            checks,
            "rescan updates the existing database",
            updated_scan["id"] == 2 and updated_scan["file_count"] == 9,
            f"scan id=2, files={updated_scan['file_count']}",
        )
        util = _json_command(
            fixture,
            "updated util query",
            [
                "--db",
                str(fixture.database),
                "file",
                "services/shared_util.py",
            ],
        )
        _check(
            checks,
            "new top contributor reassigns the file",
            util["field_id"] == "DATA"
            and util["top_employee_id"] == "3001"
            and util["churn"] == 100,
            "DATA / 3001 / churn 100",
        )
        data_field = _json_command(
            fixture,
            "updated DATA field query",
            ["--db", str(fixture.database), "field", "DATA"],
        )
        _check(
            checks,
            "incremental queries see new files",
            {item["path"] for item in data_field["files"]}
            == {"analytics/events.sql", "services/shared_util.py"},
            "DATA contains analytics/events.sql and services/shared_util.py",
        )
        print(
            f"[9] rescan           scan=#{updated_scan['id']} files={updated_scan['file_count']} "
            f"util={util['field_id']}/{util['top_employee_id']}"
        )

        if args.report:
            report_path = Path(args.report).expanduser().resolve()
            report_path.parent.mkdir(parents=True, exist_ok=True)
            report_path.write_text(
                _markdown_report(
                    checks,
                    initial,
                    search_field,
                    alice,
                    legacy,
                    gateway,
                    notes,
                    updated,
                    util,
                ),
                encoding="utf-8",
            )
            print(f"[10] report          {report_path}")

        print()
        print(f"PASS: {len(checks)} acceptance checks")
        return 0
    finally:
        if temp_handle is not None:
            temp_handle.cleanup()


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        sys.exit(1)
